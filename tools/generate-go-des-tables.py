#!/usr/bin/env python3
"""Translate the pinned Go DES constants into private Rust source tables.

Pass the Go 1.26.9 crypto/des directory. This reads and translates source;
it does not execute a cipher, compare behavior, or qualify cryptography.
"""

import hashlib
from pathlib import Path
import re
import sys


source = (Path(sys.argv[1]) / "const.go").read_bytes()
if hashlib.sha256(source).hexdigest() != "fb1b9ff9539a17a3cffd374e75bfcedbebbaf23732365af56003f04697c6c3b9":
    raise ValueError("unexpected Go DES constants source")
text = re.sub(r"//[^\n]*", "", source.decode())


def numbers(name: str, dimensions: str, count: int) -> list[int]:
    ending = r"^\}" if dimensions.count("[") > 1 else r"\}"
    body = re.search(rf"var {name} = {re.escape(dimensions)}(?:byte|uint8)\{{(.*?){ending}", text, re.S | re.M)[1]
    result = [int(value) for value in re.findall(r"\d+", body)]
    if len(result) != count:
        raise ValueError(f"unexpected table shape: {name}")
    return result


output = ["""// Generated by tools/generate-go-des-tables.py. Do not edit.
// Copyright 2010 The Go Authors. All rights reserved.
// SPDX-License-Identifier: BSD-3-Clause
// Go 1.26.9 crypto/des/const.go; see LICENSE-GO-STDLIB and UPSTREAM.md.
"""]
for go_name, rust_name, count in [
    ("initialPermutation", "INITIAL", 64),
    ("finalPermutation", "FINAL", 64),
    ("expansionFunction", "EXPANSION", 48),
    ("permutationFunction", "PERMUTATION", 32),
    ("permutedChoice1", "KEY_CHOICE_1", 56),
    ("permutedChoice2", "KEY_CHOICE_2", 48),
    ("ksRotations", "KEY_ROTATIONS", 16),
]:
    values = numbers(go_name, f"[{count}]", count)
    output.append(f"pub(super) const {rust_name}: [u8; {count}] = [\n")
    for start in range(0, count, 8):
        output.append("    " + ", ".join(map(str, values[start:start + 8])) + ",\n")
    output.append("];\n")

values = numbers("sBoxes", "[8][4][16]", 512)
output.append("pub(super) const S_BOXES: [[[u8; 16]; 4]; 8] = [\n")
for box in range(8):
    output.append("    [\n")
    for row in range(4):
        start = box * 64 + row * 16
        output.append("        [" + ", ".join(map(str, values[start:start + 16])) + "],\n")
    output.append("    ],\n")
output.append("];\n")

destination = Path(__file__).resolve().parent.parent / "vendor/sqlx-core/src/net/tls/go_pem/des/tables.rs"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("".join(output))
