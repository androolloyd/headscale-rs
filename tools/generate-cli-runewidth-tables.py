#!/usr/bin/env python3
"""Translate pinned Go Unicode source tables into private CLI Rust tables.

This only reads source data and writes Rust source. It does not run either
implementation or establish behavioral parity. Pass the go-runewidth v0.0.24
and uax29 v2.7.0 module directories as the two positional arguments.
"""

import hashlib
from pathlib import Path
import re
import sys


def source(path: Path, digest: str) -> str:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"unexpected pinned source: {path}")
    return data.decode()


def intervals(text: str, name: str) -> list[tuple[int, int]]:
    body = re.search(rf"var {name} = table\{{(.*?)\n\}}", text, re.S)[1]
    return [(int(a, 16), int(b, 16)) for a, b in
            re.findall(r"\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\}", body)]


def array(text: str, name: str) -> list[int]:
    match = re.search(rf"var {name} = \[(\d+)\]property\{{(.*?)\n\}}", text, re.S)
    values = [0] * int(match[1])
    body = re.sub(r"//[^\n]*", "", match[2])
    index = 0
    for element in body.split(","):
        if not element.strip():
            continue
        if ":" in element:
            key, element = element.split(":")
            index = int(key.strip(), 0)
        values[index] = int(element.strip(), 0)
        index += 1
    return values


runewidth, uax29 = map(Path, sys.argv[1:])
width_source = source(runewidth / "runewidth.go",
                      "3895be6a83042cf43db221ccf43db5f182b1c7dd7ce4a4ce97cdebf3fd40e786")
width_tables = source(runewidth / "runewidth_table.go",
                      "ebf377ad8197b3a52bcb372f332e15a3233152d345ba5af76cc25344f0027d7e")
trie_source = source(uax29 / "graphemes/trie.go",
                     "3182d14c05afe4d1f11b51227abc9714d3bbe6e15758285cf42de7477c9309d4")
values = array(trie_source, "graphemesValues")
indices = array(trie_source, "graphemesIndex")


def property_for_scalar(rune: int) -> int:
    # Translate the pinned UTF-8 trie into scalar ranges, without replacing its
    # Unicode properties with the Python interpreter's Unicode database.
    encoded = chr(rune).encode()
    if len(encoded) == 1:
        return values[encoded[0]]
    block = indices[encoded[0]]
    for byte in encoded[1:-1]:
        block = indices[(block << 6) + byte]
    return values[(block << 6) + encoded[-1]]


properties: list[tuple[int, int, int]] = []
for rune in range(0x110000):
    if 0xD800 <= rune <= 0xDFFF:
        continue
    prop = property_for_scalar(rune)
    if prop == 0:
        continue
    if properties and properties[-1][1] + 1 == rune and properties[-1][2] == prop:
        first, _, _ = properties[-1]
        properties[-1] = (first, rune, prop)
    else:
        properties.append((rune, rune, prop))

out = ["""// Generated by tools/generate-cli-runewidth-tables.py. Do not edit.
// Copyright (c) 2016 Yasuhiro Matsumoto
// Copyright (c) 2020 Matt Sherman
// SPDX-License-Identifier: MIT
// Source pins, SHA-256 digests and original licenses: NOTICE-PTERM,
// LICENSE-GO-RUNEWIDTH and LICENSE-UAX29. Properties are Unicode 17.0.0.
"""]
for name in ("combining", "nonprint", "doublewidth", "ambiguous"):
    data = intervals(width_source if name == "nonprint" else width_tables, name)
    out.append(f"pub(super) static {name.upper()}: &[(u32, u32)] = &[\n")
    out.extend(f"    (0x{lo:X}, 0x{hi:X}),\n" for lo, hi in data)
    out.append("];\n\n")
out.append("pub(super) static GRAPHEME_PROPERTIES: &[(u32, u32, u32)] = &[\n")
out.extend(f"    (0x{lo:X}, 0x{hi:X}, 0x{prop:X}),\n" for lo, hi, prop in properties)
out.append("];\n")
destination = Path(__file__).resolve().parents[1] / "headscale-cli/src/admin/output/runewidth/tables.rs"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("".join(out))
